"""Durable label retry timing; desired labels are always read from authoritative facts.

Install ``FLOW_LABEL_SCHEMA`` after the Flow/owner/round/delivery tables. No workflow
writer needs to enqueue an event: seeding rediscovers targets after any restart.
"""

from __future__ import annotations

from collections.abc import AsyncIterator
from contextlib import asynccontextmanager
from datetime import datetime, timedelta
from typing import Literal

import psycopg
from psycopg.rows import class_row
from pydantic import BaseModel, ConfigDict

from app.domain.models import FlowState
from app.github import GitHubError, retry_delay
from app.persistence.repository import Repository

FLOW_LABEL_SCHEMA = """
CREATE TABLE IF NOT EXISTS flow_label_targets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 repo TEXT NOT NULL, number INTEGER NOT NULL,
 next_at TIMESTAMPTZ NOT NULL, failures INTEGER NOT NULL DEFAULT 0,
 last_error TEXT, UNIQUE(repo,number)
);
CREATE INDEX IF NOT EXISTS ix_flow_label_due ON flow_label_targets(next_at,id);

CREATE OR REPLACE VIEW flow_label_desired AS
 SELECT lower(o.repo) AS repo,o.issue_number AS number,'issue'::text AS kind,
        f.id AS flow_id,f.current_round_no AS round_no,o.version AS owner_version,
        f.installation_id,f.state
 FROM issue_flow_owners o JOIN flows f ON f.id=o.flow_id
   AND lower(f.repo)=lower(o.repo) AND f.issue_number=o.issue_number
 UNION ALL
 SELECT lower(f.repo),d.pr_number,'pr',f.id,f.current_round_no,0,
        f.installation_id,f.state
 FROM flows f JOIN flow_deliveries d ON d.flow_id=f.id
 WHERE d.pr_number IS NOT NULL AND NOT EXISTS (
   SELECT 1 FROM flow_rounds r
   WHERE lower(r.repo)=lower(f.repo) AND r.pr_number=d.pr_number)
 UNION ALL
 SELECT lower(r.repo),r.pr_number,'pr',f.id,r.round_no,0,
        f.installation_id,'archived'
 FROM flow_rounds r JOIN flows f ON f.id=r.flow_id WHERE r.pr_number IS NOT NULL;
"""


class LabelTarget(BaseModel):
    """Remote identity and retry timing, never a saved desired status."""

    id: int
    repo: str
    number: int
    next_at: datetime
    failures: int
    last_error: str | None


class LabelDesired(BaseModel):
    """Immutable authority fence for one attempt, including Issue owner and round."""

    model_config = ConfigDict(frozen=True)
    repo: str
    number: int
    kind: Literal["issue", "pr"]
    flow_id: int
    round_no: int
    owner_version: int
    installation_id: int | None
    state: FlowState


class FlowLabelStore(Repository):
    """Keep bounded, retryable target scans separate from Flow transactions."""

    def seed(self, limit: int) -> None:
        """Discover missing Issues/current PRs/historical PRs without an event cursor."""
        with self._db.connection() as connection:
            connection.execute(
                "INSERT INTO flow_label_targets(repo,number,next_at)"
                " SELECT DISTINCT d.repo,d.number,%s::timestamptz FROM flow_label_desired d"
                " WHERE NOT EXISTS (SELECT 1 FROM flow_label_targets t"
                " WHERE t.repo=d.repo AND t.number=d.number)"
                " ORDER BY d.repo,d.number LIMIT %s ON CONFLICT DO NOTHING",
                (self._db.now(), limit),
            )

    def due(self, limit: int) -> list[LabelTarget]:
        with self._db.connection() as connection:
            return (
                connection.cursor(row_factory=class_row(LabelTarget))
                .execute(
                    "SELECT * FROM flow_label_targets WHERE next_at<=%s ORDER BY next_at,id LIMIT %s",
                    (self._db.now(), limit),
                )
                .fetchall()
            )

    def get(self, identity: int) -> LabelTarget:
        with self._db.connection() as connection:
            row = (
                connection.cursor(row_factory=class_row(LabelTarget))
                .execute(
                    "SELECT * FROM flow_label_targets WHERE id=%s",
                    (identity,),
                )
                .fetchone()
            )
        assert row is not None
        return row

    def desired(self, row: LabelTarget) -> LabelDesired | None:
        """An old Flow/event cannot select the Issue owner or supply a cached state."""
        with self._db.connection() as connection:
            return (
                connection.cursor(row_factory=class_row(LabelDesired))
                .execute(
                    "SELECT * FROM flow_label_desired WHERE repo=%s AND number=%s",
                    (row.repo, row.number),
                )
                .fetchone()
            )

    def checked(self, row: LabelTarget, desired: LabelDesired | None, interval: float) -> None:
        """Recheck after I/O; even an unchanged observation expires, never confirms forever."""
        with self._db.transaction() as tx, tx.connection() as connection:
            unchanged = FlowLabelStore(tx).desired(row) == desired
            connection.execute(
                "UPDATE flow_label_targets SET failures=0,last_error=NULL,next_at=%s WHERE id=%s",
                (tx.now() + timedelta(seconds=interval if unchanged else 0), row.id),
            )

    def changed(self, row: LabelTarget) -> None:
        """Retry immediately when authority changed across a remote operation."""
        with self._db.connection() as connection:
            connection.execute(
                "UPDATE flow_label_targets SET next_at=%s,failures=0,last_error=NULL WHERE id=%s",
                (self._db.now(), row.id),
            )

    def failed(self, row: LabelTarget, error: GitHubError) -> None:
        """Permissions/deleted labels can recover too; no failure is a permanent acknowledgement."""
        attempts, now = row.failures + 1, self._db.now()
        delay = max(0 if error.retryable else 300, retry_delay(attempts, now, error))
        with self._db.connection() as connection:
            connection.execute(
                "UPDATE flow_label_targets SET failures=%s,last_error=%s,next_at=%s WHERE id=%s",
                (attempts, str(error), now + timedelta(seconds=delay), row.id),
            )

    @asynccontextmanager
    async def claim(self, row: LabelTarget) -> AsyncIterator[bool]:
        """Serialize a repository/number across controllers, without locking workflow rows."""
        # Like Projects, a separate session spans I/O; cancellation/exit releases the lock.
        async with await psycopg.AsyncConnection.connect(
            self._db.database_url,
            autocommit=True,
        ) as connection:
            cursor = await connection.execute(
                "SELECT pg_try_advisory_lock(hashtextextended(%s,2))",
                (f"flow-labels:{row.repo}#{row.number}",),
            )
            acquired = await cursor.fetchone()
            yield bool(acquired and acquired[0])
