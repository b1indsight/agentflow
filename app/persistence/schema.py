"""Complete PostgreSQL schema in dependency order; no historical migrations."""

from app.persistence.console_schema import CONSOLE_SCHEMA

SCHEMA = """
CREATE TABLE IF NOT EXISTS runtime_settings (
  id INTEGER PRIMARY KEY CHECK (id=1),
  codex_model TEXT,
  amp_model TEXT,
  codex_effort TEXT,
  amp_effort TEXT,
  revision BIGINT NOT NULL DEFAULT 0 CHECK (revision>=0)
);
INSERT INTO runtime_settings(id) VALUES (1) ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS flows (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  repo TEXT NOT NULL,
  issue_number INTEGER,
  task_content TEXT,
  title TEXT,
  title_job_id BIGINT,
  installation_id BIGINT,
  state TEXT NOT NULL CHECK (state IN ('queued','running','review','blocked','finalizing','archived')),
  current_attempt_id BIGINT,
  archive_reason TEXT CHECK (archive_reason IN ('succeeded','abandoned')),
  archive_summary TEXT,
  archived_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL,
  is_issue_owner BOOLEAN NOT NULL DEFAULT FALSE CHECK (NOT is_issue_owner OR issue_number IS NOT NULL),
  history_only BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT flows_one_input CHECK ((issue_number IS NULL) = (task_content IS NOT NULL)),
  CONSTRAINT flows_history_archived CHECK (NOT history_only OR state='archived'),
  CHECK ((state='archived') = (archived_at IS NOT NULL)),
  CHECK (state NOT IN ('finalizing','archived') OR archive_reason IS NOT NULL),
  CHECK (archive_reason IS NULL OR state IN ('blocked','finalizing','archived'))
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_flows_active ON flows(repo, issue_number) WHERE state <> 'archived';
CREATE UNIQUE INDEX IF NOT EXISTS ux_flows_issue_owner ON flows(repo,issue_number) WHERE is_issue_owner;
CREATE TABLE IF NOT EXISTS attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flow_id BIGINT NOT NULL REFERENCES flows(id),
  UNIQUE(flow_id,id),
  delivery_branch TEXT, delivery_base_branch TEXT, delivery_state TEXT, delivery_pr_number INTEGER,
  delivery_url TEXT, delivery_head_sha TEXT, delivery_title TEXT, delivery_body TEXT,
  delivery_merged_at TIMESTAMPTZ, delivery_merge_commit_sha TEXT, delivery_version INTEGER,
  delivery_created_at TIMESTAMPTZ, delivery_updated_at TIMESTAMPTZ,
  CONSTRAINT attempts_delivery_complete CHECK (
    ROW(delivery_branch,delivery_base_branch,delivery_state,delivery_pr_number,delivery_url,
        delivery_head_sha,delivery_title,delivery_body,delivery_merged_at,delivery_merge_commit_sha,
        delivery_version,delivery_created_at,delivery_updated_at) IS NULL
    OR (delivery_branch IS NOT NULL AND delivery_state IS NOT NULL AND delivery_version IS NOT NULL
        AND delivery_created_at IS NOT NULL AND delivery_updated_at IS NOT NULL)),
  codex_session_id TEXT,
  session_generation INTEGER NOT NULL DEFAULT 0,
  last_revision_summary TEXT NOT NULL DEFAULT '',
  revision_cycles INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_attempts_delivery_pr ON attempts(delivery_pr_number) WHERE delivery_pr_number IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_attempts_delivery_head ON attempts(delivery_head_sha) WHERE delivery_head_sha IS NOT NULL;

DO $$
BEGIN
  ALTER TABLE flows
    ADD CONSTRAINT fk_flows_current_attempt
    FOREIGN KEY (id,current_attempt_id) REFERENCES attempts(flow_id,id);
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;
-- Circular ownership permits a transient NULL during creation/reopening, never after commit.
CREATE OR REPLACE FUNCTION require_selected_attempt() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM flows WHERE id=NEW.id AND current_attempt_id IS NULL) THEN
    RAISE EXCEPTION 'Flow requires a selected Attempt' USING ERRCODE='23514';
  END IF;
  RETURN NULL;
END $$;
DO $$ BEGIN
  CREATE CONSTRAINT TRIGGER require_selected_attempt AFTER INSERT OR UPDATE OF current_attempt_id ON flows
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW WHEN (NEW.current_attempt_id IS NULL)
    EXECUTE FUNCTION require_selected_attempt();
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

CREATE TABLE IF NOT EXISTS jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flow_id BIGINT REFERENCES flows(id),
  attempt_id BIGINT,
  FOREIGN KEY (flow_id,attempt_id) REFERENCES attempts(flow_id,id) MATCH FULL,
  kind TEXT NOT NULL,
  state TEXT NOT NULL,
  attempt INTEGER NOT NULL DEFAULT 0,
  heartbeat_at TIMESTAMPTZ,
  assigned_worker_id TEXT,
  workspace TEXT,
  generation BIGINT CHECK (generation>0),
  assignment_token TEXT,
  started_at TIMESTAMPTZ,
  dispatch_authorized_at TIMESTAMPTZ,
  lease_expires_at TIMESTAMPTZ,
  recovery_deadline TIMESTAMPTZ,
  prepare_failures INTEGER NOT NULL DEFAULT 0,
  prepare_next_at TIMESTAMPTZ,
  prepare_first_failed_at TIMESTAMPTZ,
  prepare_last_error TEXT,
  result_payload JSONB,
  result_digest TEXT,
  result_received_at TIMESTAMPTZ,
  result_applied_at TIMESTAMPTZ,
  verify_failures INTEGER NOT NULL DEFAULT 0,
  verify_next_at TIMESTAMPTZ,
  verify_last_error TEXT,
  source_job_id BIGINT REFERENCES jobs(id),
  source_key TEXT,
  last_error TEXT,
  payload JSONB,
  inference JSONB,
  CONSTRAINT ck_jobs_kind_fields CHECK (
    (kind='inference' AND inference IS NOT NULL)
    OR (kind<>'inference' AND flow_id IS NOT NULL AND inference IS NULL)),
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_jobs_state ON jobs(state);
CREATE UNIQUE INDEX IF NOT EXISTS ux_jobs_inference_request
  ON jobs ((inference->'task'->>'request_id')) WHERE kind='inference';
CREATE OR REPLACE FUNCTION preserve_job_owner() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (OLD.flow_id,OLD.attempt_id) IS DISTINCT FROM (NEW.flow_id,NEW.attempt_id) THEN
    RAISE EXCEPTION 'job ownership is immutable' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER preserve_job_owner BEFORE UPDATE OF flow_id,attempt_id ON jobs
  FOR EACH ROW EXECUTE FUNCTION preserve_job_owner();

CREATE TABLE IF NOT EXISTS workers (
  worker_id TEXT NOT NULL,
  workspace TEXT NOT NULL CHECK (workspace ~ '^[0-9a-f]{32}$'),
  repository TEXT,
  generation BIGINT NOT NULL DEFAULT 1 CHECK (generation>0),
  inventory_epoch TEXT,
  repo_workspace_limit INTEGER NOT NULL DEFAULT 2 CHECK (repo_workspace_limit>0),
  protocol_version INTEGER NOT NULL,
  status TEXT NOT NULL,
  connection_epoch TEXT,
  draining BOOLEAN NOT NULL DEFAULT FALSE,
  current_job_id BIGINT,
  first_connected_at TIMESTAMPTZ NOT NULL,
  last_connected_at TIMESTAMPTZ NOT NULL,
  last_seen_at TIMESTAMPTZ NOT NULL,
  last_assigned_at TIMESTAMPTZ,
  last_error TEXT,
  last_disconnect_reason TEXT,
  coding_agent TEXT CHECK (coding_agent IN ('codex','amp')),
  execute BOOLEAN NOT NULL DEFAULT TRUE,
  inference JSONB,
  current_inference_job_id BIGINT REFERENCES jobs(id),
  last_inference_assigned_at TIMESTAMPTZ,
  PRIMARY KEY(worker_id,workspace)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_workers_default ON workers(worker_id) WHERE repository IS NULL;

CREATE TABLE IF NOT EXISTS worker_file_links (
  link_id TEXT PRIMARY KEY,
  worker_id TEXT NOT NULL,
  file_id TEXT NOT NULL,
  UNIQUE(worker_id, file_id)
);

CREATE TABLE IF NOT EXISTS flow_executions (
  flow_id BIGINT PRIMARY KEY REFERENCES flows(id),
  worker_id TEXT NOT NULL,
  workspace TEXT NOT NULL,
  generation BIGINT NOT NULL CHECK (generation>0),
  repo_identity TEXT NOT NULL,
  bound_at TIMESTAMPTZ NOT NULL,
  recovery_deadline TIMESTAMPTZ,
  released_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_flow_executions_workspace_active
  ON flow_executions(worker_id,workspace) WHERE released_at IS NULL;

CREATE TABLE IF NOT EXISTS flow_tool_calls (
  call_id TEXT PRIMARY KEY,
  flow_id BIGINT NOT NULL REFERENCES flows(id),
  attempt_id BIGINT NOT NULL REFERENCES attempts(id),
  job_id BIGINT NOT NULL REFERENCES jobs(id),
  name TEXT NOT NULL,
  arguments JSONB NOT NULL,
  response JSONB,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_jobs_lease ON jobs(lease_expires_at)
  WHERE state='running' AND started_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_jobs_recovery ON jobs(recovery_deadline)
  WHERE state='running' AND started_at IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_jobs_result_pending ON jobs(result_received_at)
  WHERE state='running' AND result_received_at IS NOT NULL AND result_applied_at IS NULL;

CREATE TABLE IF NOT EXISTS events (
  delivery_id TEXT PRIMARY KEY,
  event_type TEXT NOT NULL,
  flow_id BIGINT REFERENCES flows(id),
  payload JSONB,
  recorded_at TIMESTAMPTZ,
  inbox_position BIGINT, body_digest TEXT, received_at TIMESTAMPTZ, state TEXT, attempts INTEGER,
  next_at TIMESTAMPTZ, claim_token TEXT, claim_expires_at TIMESTAMPTZ, processed_at TIMESTAMPTZ, error_code TEXT,
  CONSTRAINT ck_event_receipt CHECK (
    (inbox_position IS NULL AND recorded_at IS NOT NULL AND body_digest IS NULL AND received_at IS NULL
     AND state IS NULL AND attempts IS NULL AND next_at IS NULL AND claim_token IS NULL
     AND claim_expires_at IS NULL AND processed_at IS NULL AND error_code IS NULL)
    OR (inbox_position IS NOT NULL AND body_digest IS NOT NULL AND received_at IS NOT NULL
        AND state IS NOT NULL AND attempts IS NOT NULL AND next_at IS NOT NULL))
);
CREATE SEQUENCE IF NOT EXISTS events_inbox_position_seq OWNED BY events.inbox_position;
CREATE UNIQUE INDEX IF NOT EXISTS ux_events_inbox_position ON events(inbox_position) WHERE inbox_position IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_webhook_pending ON events(state, next_at, received_at) WHERE state IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_webhook_order ON events
 ((payload #>> '{repository,full_name}'), inbox_position) WHERE state != 'done';
"""

STOP_SCHEMA = """
CREATE TABLE IF NOT EXISTS execution_stops (
 request_id TEXT PRIMARY KEY, flow_id BIGINT NOT NULL REFERENCES flows(id),
 job_id BIGINT NOT NULL REFERENCES jobs(id), worker_id TEXT NOT NULL,
 workspace TEXT NOT NULL, generation BIGINT NOT NULL CHECK (generation>0),
 assignment_token TEXT NOT NULL, binding_at TIMESTAMPTZ NOT NULL,
 reason TEXT NOT NULL DEFAULT 'cancelled', requested_at TIMESTAMPTZ NOT NULL,
 state TEXT NOT NULL DEFAULT 'pending', confirmed_at TIMESTAMPTZ, receipt_digest TEXT,
 UNIQUE(job_id,assignment_token)
);
CREATE INDEX IF NOT EXISTS ix_stops_worker ON execution_stops(worker_id) WHERE state!='confirmed';
"""

RESULT_SCHEMA = """
CREATE UNIQUE INDEX IF NOT EXISTS ux_jobs_source ON jobs(source_job_id, source_key)
  WHERE source_job_id IS NOT NULL;
CREATE TABLE IF NOT EXISTS result_applications (
  job_id BIGINT PRIMARY KEY REFERENCES jobs(id),
  digest TEXT NOT NULL,
  plan JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS result_effects (
  job_id BIGINT NOT NULL REFERENCES result_applications(job_id),
  effect_key TEXT NOT NULL,
  position INTEGER NOT NULL,
  payload JSONB NOT NULL,
  state TEXT NOT NULL,
  receipt JSONB,
  claimed_by TEXT,
  claim_expires_at TIMESTAMPTZ,
  dispatched_at TIMESTAMPTZ,
  attempts INTEGER NOT NULL DEFAULT 0,
  next_attempt_at TIMESTAMPTZ NOT NULL,
  last_error TEXT,
  PRIMARY KEY(job_id, effect_key),
  UNIQUE(job_id, position)
);
CREATE INDEX IF NOT EXISTS ix_result_effects_due ON result_effects(next_attempt_at)
  WHERE state NOT IN ('succeeded','failed','skipped');
"""

REVIEW_SCHEMA = """
-- One row per content version of a GitHub feedback object; objects are global, not per Flow.
-- New objects encode item_id as github_id*4+kind code; upgraded objects keep their frozen IDs.
CREATE TABLE IF NOT EXISTS review_versions (
  item_id BIGINT NOT NULL,
  version INTEGER NOT NULL,
  kind TEXT NOT NULL CONSTRAINT ck_review_versions_kind
    CHECK (kind IN ('review_body','inline','conversation')),
  github_id BIGINT NOT NULL CONSTRAINT ck_review_versions_github_id CHECK (github_id>0),
  observed_at TIMESTAMPTZ NOT NULL,
  attempt_id BIGINT NOT NULL REFERENCES attempts(id),
  source_delivery TEXT,
  content JSONB NOT NULL,
  relayed_at TIMESTAMPTZ,
  consumed_at TIMESTAMPTZ,
  addressed_sha TEXT,
  addressed_job_id BIGINT REFERENCES jobs(id),
  observation_seq BIGINT GENERATED ALWAYS AS IDENTITY,
  PRIMARY KEY(item_id,version)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_review_observation_seq ON review_versions(observation_seq);
CREATE UNIQUE INDEX IF NOT EXISTS ux_review_object_version ON review_versions(kind,github_id,version);
CREATE INDEX IF NOT EXISTS ix_review_versions_attempt ON review_versions(attempt_id);
CREATE TABLE IF NOT EXISTS review_buffers (
  flow_id BIGINT PRIMARY KEY REFERENCES flows(id),
  due_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ix_review_due ON review_buffers(due_at) WHERE due_at IS NOT NULL;
CREATE TABLE IF NOT EXISTS review_batches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flow_id BIGINT NOT NULL REFERENCES flows(id),
  attempt_id BIGINT NOT NULL REFERENCES attempts(id),
  state TEXT NOT NULL CHECK(state IN ('ready','processing','waiting','completed','cancelled')),
  trigger TEXT NOT NULL,
  job_id BIGINT REFERENCES jobs(id),
  feedback JSONB NOT NULL,
  open_points JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  context JSONB,
  decision JSONB,
  threads JSONB,
  inference_job_id BIGINT REFERENCES jobs(id)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_review_active_batch ON review_batches(flow_id)
  WHERE state IN ('ready','processing');
"""

RECONCILE_SCHEMA = """
-- One scheduled GitHub check per Flow and source: the PR status ('pull_request') or a feedback source.
CREATE TABLE IF NOT EXISTS reconcile_checks (
  flow_id BIGINT NOT NULL REFERENCES flows(id),
  source TEXT NOT NULL,
  cursor TEXT,
  next_at TIMESTAMPTZ NOT NULL,
  last_success_at TIMESTAMPTZ,
  failures INTEGER NOT NULL DEFAULT 0,
  last_error TEXT,
  scan_incomplete BOOLEAN NOT NULL DEFAULT FALSE,
  hint_version BIGINT NOT NULL DEFAULT 0,
  PRIMARY KEY(flow_id,source)
);
CREATE INDEX IF NOT EXISTS ix_reconcile_checks_due ON reconcile_checks(next_at,flow_id);
"""

PROJECT_SCHEMA = """
CREATE TABLE IF NOT EXISTS project_destinations (
  repo TEXT NOT NULL, project_id TEXT NOT NULL, enabled_at TIMESTAMPTZ NOT NULL,
  PRIMARY KEY(repo,project_id)
);
CREATE TABLE IF NOT EXISTS project_projections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  repo TEXT NOT NULL, issue_number INTEGER NOT NULL, project_id TEXT NOT NULL,
  content_id TEXT, flow_id BIGINT NOT NULL REFERENCES flows(id), item_id TEXT,
  config_key TEXT NOT NULL, desired_status TEXT NOT NULL, desired_version BIGINT NOT NULL DEFAULT 1,
  synced_version BIGINT NOT NULL DEFAULT 0, next_at TIMESTAMPTZ NOT NULL,
  failures INTEGER NOT NULL DEFAULT 0, last_error TEXT, blocked BOOLEAN NOT NULL DEFAULT FALSE,
  cursor TEXT, scan_incomplete BOOLEAN NOT NULL DEFAULT FALSE, add_started BOOLEAN NOT NULL DEFAULT FALSE,
  UNIQUE(project_id,repo,issue_number), UNIQUE(project_id,content_id)
);
CREATE INDEX IF NOT EXISTS ix_projects_due ON project_projections(next_at,id) WHERE NOT blocked;
"""

