"""PostgreSQL 持久层：schema + 仓储。见 docs/plan/postgresql-store.md。"""

from __future__ import annotations

import os
from datetime import timedelta
from typing import Any, cast

from psycopg import Connection
from psycopg.rows import class_row, dict_row
from psycopg.types.json import Jsonb
from psycopg_pool import ConnectionPool

from app.models import (
    Attempt,
    Flow,
    FlowState,
    Job,
    JobKind,
    JobState,
    ReviewItem,
    utcnow,
)

SCHEMA = """
CREATE TABLE IF NOT EXISTS flows (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  repo TEXT NOT NULL,
  issue_number INTEGER NOT NULL,
  installation_id BIGINT,
  state TEXT NOT NULL,
  current_attempt_id BIGINT,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_flows_active ON flows(repo, issue_number)
  WHERE state NOT IN ('archived','cancelled','failed');

-- 一条 flow 挂多个候选 attempt（§9-2 多方案分支）；MVP 恰好一个。
CREATE TABLE IF NOT EXISTS attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flow_id BIGINT NOT NULL REFERENCES flows(id),
  branch TEXT,
  codex_session_id TEXT,
  pr_number INTEGER,
  revision_cycles INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_attempts_flow ON attempts(flow_id);
CREATE INDEX IF NOT EXISTS ix_attempts_pr ON attempts(pr_number);

DO $$
BEGIN
  ALTER TABLE flows
    ADD CONSTRAINT fk_flows_current_attempt
    FOREIGN KEY (current_attempt_id) REFERENCES attempts(id);
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

CREATE TABLE IF NOT EXISTS jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flow_id BIGINT NOT NULL REFERENCES flows(id),
  kind TEXT NOT NULL,
  state TEXT NOT NULL,
  attempt INTEGER NOT NULL DEFAULT 0,
  pid INTEGER,
  heartbeat_at TIMESTAMPTZ,
  payload JSONB,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_jobs_state ON jobs(state);

CREATE TABLE IF NOT EXISTS events (
  delivery_id TEXT PRIMARY KEY,
  event_type TEXT NOT NULL,
  flow_id BIGINT REFERENCES flows(id),
  payload JSONB,
  processed_at TIMESTAMPTZ NOT NULL
);

-- flows → runs 一对多，归属到具体 attempt（§9-2）。
CREATE TABLE IF NOT EXISTS codex_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attempt_id BIGINT NOT NULL REFERENCES attempts(id),
  kind TEXT NOT NULL,
  prompt TEXT,
  log_path TEXT,
  exit_code INTEGER,
  started_at TIMESTAMPTZ,
  ended_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS review_threads (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attempt_id BIGINT NOT NULL REFERENCES attempts(id),
  kind TEXT NOT NULL,
  github_id BIGINT NOT NULL,
  thread_id TEXT,
  path TEXT,
  line INTEGER,
  original_commit_id TEXT,
  diff_hunk TEXT,
  author TEXT,
  body TEXT,
  relayed BOOLEAN NOT NULL DEFAULT FALSE,
  resolved BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_review_gid
  ON review_threads(attempt_id, kind, github_id);
"""

Row = dict[str, Any]


def _required[Record](row: Record | None) -> Record:
    """Fail fast when an insert/read-back invariant is violated."""
    if row is None:
        raise RuntimeError("database insert did not produce a readable record")
    return row


class Store:
    """Synchronous PostgreSQL repository backed by a small connection pool."""

    def __init__(self, database_url: str):
        self.database_url = database_url
        self._pool = cast(
            ConnectionPool[Connection[Row]],
            ConnectionPool(
                conninfo=database_url,
                min_size=1,
                max_size=4,
                open=True,
                kwargs={"row_factory": dict_row},
            ),
        )

    def init_db(self) -> None:
        with self._pool.connection() as connection:
            connection.execute(SCHEMA)

    def close(self) -> None:
        self._pool.close()

    # ------------------------------------------------------------------ flows

    def create_flow(self, repo: str, issue_number: int, installation_id: int | None) -> Flow:
        now = utcnow()
        with (
            self._pool.connection() as connection,
            connection.cursor(row_factory=class_row(Flow)) as cursor,
        ):
            row = cursor.execute(
                "INSERT INTO flows(repo, issue_number, installation_id, state, created_at,"
                " updated_at) VALUES (%s,%s,%s,%s,%s,%s) RETURNING *",
                (repo, issue_number, installation_id, FlowState.PENDING, now, now),
            ).fetchone()
        return _required(row)

    def get_flow(self, flow_id: int) -> Flow | None:
        with (
            self._pool.connection() as connection,
            connection.cursor(row_factory=class_row(Flow)) as cursor,
        ):
            return cursor.execute("SELECT * FROM flows WHERE id=%s", (flow_id,)).fetchone()

    def get_active_flow(self, repo: str, issue_number: int) -> Flow | None:
        with (
            self._pool.connection() as connection,
            connection.cursor(row_factory=class_row(Flow)) as cursor,
        ):
            return cursor.execute(
                "SELECT * FROM flows WHERE repo=%s AND issue_number=%s AND state NOT IN"
                " ('archived','cancelled','failed') ORDER BY id DESC LIMIT 1",
                (repo, issue_number),
            ).fetchone()

    def get_flow_by_pr(self, repo: str, pr_number: int) -> Flow | None:
        with (
            self._pool.connection() as connection,
            connection.cursor(row_factory=class_row(Flow)) as cursor,
        ):
            return cursor.execute(
                "SELECT f.* FROM flows f JOIN attempts a ON a.flow_id=f.id"
                " WHERE f.repo=%s AND a.pr_number=%s ORDER BY f.id DESC LIMIT 1",
                (repo, pr_number),
            ).fetchone()

    def update_flow(self, flow: Flow) -> None:
        flow.updated_at = utcnow()
        with self._pool.connection() as connection:
            connection.execute(
                "UPDATE flows SET installation_id=%s, state=%s, current_attempt_id=%s,"
                " updated_at=%s WHERE id=%s",
                (
                    flow.installation_id,
                    flow.state,
                    flow.current_attempt_id,
                    flow.updated_at,
                    flow.id,
                ),
            )

    def list_flows(self, *, active_only: bool = False) -> list[Flow]:
        query = "SELECT * FROM flows"
        if active_only:
            query += " WHERE state NOT IN ('archived','cancelled','failed')"
        query += " ORDER BY id DESC"
        with (
            self._pool.connection() as connection,
            connection.cursor(row_factory=class_row(Flow)) as cursor,
        ):
            return cursor.execute(query).fetchall()

    # --------------------------------------------------------------- attempts

    def create_attempt(self, flow_id: int) -> Attempt:
        now = utcnow()
        with (
            self._pool.connection() as connection,
            connection.cursor(row_factory=class_row(Attempt)) as cursor,
        ):
            row = cursor.execute(
                "INSERT INTO attempts(flow_id, revision_cycles, created_at, updated_at)"
                " VALUES (%s,%s,%s,%s) RETURNING *",
                (flow_id, 0, now, now),
            ).fetchone()
        return _required(row)

    def get_attempt(self, attempt_id: int) -> Attempt | None:
        with (
            self._pool.connection() as connection,
            connection.cursor(row_factory=class_row(Attempt)) as cursor,
        ):
            return cursor.execute("SELECT * FROM attempts WHERE id=%s", (attempt_id,)).fetchone()

    def get_current_attempt(self, flow: Flow) -> Attempt | None:
        return self.get_attempt(flow.current_attempt_id) if flow.current_attempt_id else None

    def list_attempts(self, flow_id: int) -> list[Attempt]:
        with (
            self._pool.connection() as connection,
            connection.cursor(row_factory=class_row(Attempt)) as cursor,
        ):
            return cursor.execute(
                "SELECT * FROM attempts WHERE flow_id=%s ORDER BY id", (flow_id,)
            ).fetchall()

    def update_attempt(self, attempt: Attempt) -> None:
        attempt.updated_at = utcnow()
        with self._pool.connection() as connection:
            connection.execute(
                "UPDATE attempts SET branch=%s, codex_session_id=%s, pr_number=%s,"
                " revision_cycles=%s, updated_at=%s WHERE id=%s",
                (
                    attempt.branch,
                    attempt.codex_session_id,
                    attempt.pr_number,
                    attempt.revision_cycles,
                    attempt.updated_at,
                    attempt.id,
                ),
            )

    # ------------------------------------------------------------------- jobs

    def enqueue_job(self, flow_id: int, kind: JobKind, payload: dict | None = None) -> Job:
        now = utcnow()
        with (
            self._pool.connection() as connection,
            connection.cursor(row_factory=class_row(Job)) as cursor,
        ):
            row = cursor.execute(
                "INSERT INTO jobs(flow_id, kind, state, attempt, payload, created_at,"
                " updated_at) VALUES (%s,%s,%s,%s,%s,%s,%s) RETURNING *",
                (
                    flow_id,
                    kind,
                    JobState.QUEUED,
                    0,
                    Jsonb(payload) if payload else None,
                    now,
                    now,
                ),
            ).fetchone()
        return _required(row)

    def get_job(self, job_id: int) -> Job | None:
        with (
            self._pool.connection() as connection,
            connection.cursor(row_factory=class_row(Job)) as cursor,
        ):
            return cursor.execute("SELECT * FROM jobs WHERE id=%s", (job_id,)).fetchone()

    def claim_job(self) -> Job | None:
        """Atomically claim the oldest queued job without blocking another consumer."""
        now = utcnow()
        with (
            self._pool.connection() as connection,
            connection.cursor(row_factory=class_row(Job)) as cursor,
        ):
            return cursor.execute(
                "WITH next_job AS ("
                " SELECT id FROM jobs WHERE state=%s ORDER BY id"
                " FOR UPDATE SKIP LOCKED LIMIT 1"
                ")"
                " UPDATE jobs SET state=%s, pid=%s, attempt=attempt+1, heartbeat_at=%s,"
                " updated_at=%s FROM next_job WHERE jobs.id=next_job.id RETURNING jobs.*",
                (JobState.QUEUED, JobState.RUNNING, os.getpid(), now, now),
            ).fetchone()

    def heartbeat(self, job_id: int) -> None:
        now = utcnow()
        with self._pool.connection() as connection:
            connection.execute(
                "UPDATE jobs SET heartbeat_at=%s, updated_at=%s WHERE id=%s",
                (now, now, job_id),
            )

    def finish_job(self, job_id: int, state: JobState) -> None:
        with self._pool.connection() as connection:
            connection.execute(
                "UPDATE jobs SET state=%s, updated_at=%s WHERE id=%s",
                (state, utcnow(), job_id),
            )

    def recover_stale_jobs(self, stale_after_seconds: float = 300.0) -> int:
        """Requeue running jobs whose heartbeat has expired."""
        cutoff = utcnow() - timedelta(seconds=stale_after_seconds)
        with self._pool.connection() as connection:
            result = connection.execute(
                "UPDATE jobs SET state=%s, pid=NULL, updated_at=%s WHERE state=%s"
                " AND (heartbeat_at IS NULL OR heartbeat_at < %s)",
                (JobState.QUEUED, utcnow(), JobState.RUNNING, cutoff),
            )
            recovered = result.rowcount
        return recovered

    # ----------------------------------------------------------------- events

    def event_seen(self, delivery_id: str) -> bool:
        with self._pool.connection() as connection:
            row = connection.execute(
                "SELECT 1 FROM events WHERE delivery_id=%s", (delivery_id,)
            ).fetchone()
        return row is not None

    def record_event(
        self, delivery_id: str, event_type: str, flow_id: int | None, payload: dict
    ) -> bool:
        """Atomically reserve a delivery and report whether this caller won."""
        with self._pool.connection() as connection:
            row = connection.execute(
                "INSERT INTO events(delivery_id, event_type, flow_id, payload, processed_at)"
                " VALUES (%s,%s,%s,%s,%s) ON CONFLICT (delivery_id) DO NOTHING"
                " RETURNING delivery_id",
                (delivery_id, event_type, flow_id, Jsonb(payload), utcnow()),
            ).fetchone()
        return row is not None

    # --------------------------------------------------------- review_threads

    def upsert_review_item(self, item: ReviewItem) -> None:
        with self._pool.connection() as connection:
            connection.execute(
                "INSERT INTO review_threads(attempt_id, kind, github_id, thread_id, path, line,"
                " original_commit_id, diff_hunk, author, body, relayed, resolved, created_at)"
                " VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)"
                " ON CONFLICT(attempt_id, kind, github_id) DO UPDATE SET"
                " thread_id=excluded.thread_id, body=excluded.body",
                (
                    item.attempt_id,
                    item.kind,
                    item.github_id,
                    item.thread_id,
                    item.path,
                    item.line,
                    item.original_commit_id,
                    item.diff_hunk,
                    item.author,
                    item.body,
                    item.relayed,
                    item.resolved,
                    item.created_at,
                ),
            )

    def unrelayed_items(self, attempt_id: int) -> list[ReviewItem]:
        with (
            self._pool.connection() as connection,
            connection.cursor(row_factory=class_row(ReviewItem)) as cursor,
        ):
            return cursor.execute(
                "SELECT * FROM review_threads WHERE attempt_id=%s AND relayed=FALSE ORDER BY id",
                (attempt_id,),
            ).fetchall()

    def mark_relayed(self, item_ids: list[int]) -> None:
        if not item_ids:
            return
        with self._pool.connection() as connection, connection.cursor() as cursor:
            cursor.executemany(
                "UPDATE review_threads SET relayed=TRUE WHERE id=%s",
                [(item_id,) for item_id in item_ids],
            )

    def mark_resolved(self, attempt_id: int, github_id: int) -> None:
        with self._pool.connection() as connection:
            connection.execute(
                "UPDATE review_threads SET resolved=TRUE WHERE attempt_id=%s AND github_id=%s",
                (attempt_id, github_id),
            )

    # ------------------------------------------------------------- codex_runs

    def record_codex_run(
        self, attempt_id: int, kind: str, prompt: str, log_path: str, exit_code: int
    ) -> None:
        now = utcnow()
        with self._pool.connection() as connection:
            connection.execute(
                "INSERT INTO codex_runs(attempt_id, kind, prompt, log_path, exit_code,"
                " started_at, ended_at) VALUES (%s,%s,%s,%s,%s,%s,%s)",
                (attempt_id, kind, prompt, log_path, exit_code, now, now),
            )
