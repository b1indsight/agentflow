class ReviewStore:
    """Use the owning Store's clock and explicit transaction views; never hold locks across I/O."""

    def __init__(self, store: Store) -> None:
        self.store = store

    def ingest(
        self,
        flow_id: int,
        delivery_id: str,
        event_type: str,
        payload: dict,
        update: FeedbackUpdate,
        *,
        settle_seconds: float,
        submit_grace_seconds: float,
    ) -> bool:
        """Commit delivery reservation, immutable content and the next deadline as one unit."""
        with self.store.transaction() as tx:
            flow = tx.lock_workflow(flow_id)
            if not tx.record_event(delivery_id, event_type, flow_id, payload):
                return False
            delivery = tx.get_delivery(flow_id)
            if (
                flow is None
                or flow.state in TERMINAL_STATES
                or flow.current_attempt_id is None
                or delivery is None
                or delivery.state is not DeliveryState.OPEN
            ):
                return False
            previous_body = ((payload.get("changes") or {}).get("body") or {}).get("from")
            if not tx.reviews._append_version(
                flow_id,
                flow.current_attempt_id,
                delivery_id,
                update,
                previous_body=previous_body,
            ):
                return False
            tx.reviews._reconcile_edits(flow_id, update)
            # Invalidating old content adds no discussion and must not wake a waiting batch.
            if update.deleted:
                return True
            strong = tx.reviews._has_unused_signal(flow_id)
            delay = submit_grace_seconds if strong or update.submitted else settle_seconds
            tx.reviews._touch(flow_id, delay)
            return True

    def _append_version(
        self,
        flow_id: int,
        attempt_id: int,
        delivery_id: str | None,
        update: FeedbackUpdate,
        *,
        previous_body: str | None = None,
    ) -> bool:
        with self.store.connection() as connection:
            row = connection.execute(
                "SELECT i.id,i.version,i.observed_at,v.content FROM review_items i JOIN review_versions v"
                " ON v.item_id=i.id AND v.version=i.version"
                " WHERE i.flow_id=%s AND i.kind=%s AND i.github_id=%s",
                (flow_id, update.kind, update.github_id),
            ).fetchone()
            if row is not None:
                old = FeedbackUpdate.model_validate(row["content"])
                # Deletion is final for a GitHub object ID; an out-of-order edit cannot revive it.
                if old.deleted or (update.updated_at < row["observed_at"] and not update.deleted):
                    return False
                if (
                    update.updated_at == row["observed_at"]
                    and not update.deleted
                    and previous_body != old.body
                ):
                    # Reserve the webhook once, but keep an edit whose predecessor is still missing.
                    if previous_body is not None and delivery_id is not None:
                        connection.execute(
                            "INSERT INTO review_pending_edits"
                            " (source_delivery,item_id,attempt_id,previous_body,updated_at,content)"
                            " VALUES(%s,%s,%s,%s,%s,%s) ON CONFLICT DO NOTHING",
                            (delivery_id, row["id"], attempt_id, previous_body,
                             update.updated_at, Jsonb(update.model_dump(mode="json"))),
                        )
                    return False
                content_fields = {"updated_at", "submitted"}
                if old.model_dump(exclude=content_fields) == update.model_dump(
                    exclude=content_fields
                ):
                    connection.execute(
                        "UPDATE review_items SET observed_at=%s WHERE id=%s",
                        (update.updated_at, row["id"]),
                    )
                    return False
                item_id, version = row["id"], row["version"] + 1
                connection.execute(
                    "UPDATE review_items SET version=%s,observed_at=%s WHERE id=%s",
                    (version, update.updated_at, item_id),
                )
            else:
                item = connection.execute(
                    "INSERT INTO review_items(flow_id,kind,github_id,version,observed_at)"
                    " VALUES(%s,%s,%s,1,%s)"
                    " RETURNING id",
                    (flow_id, update.kind, update.github_id, update.updated_at),
                ).fetchone()
                assert item is not None
                item_id, version = item["id"], 1
            connection.execute(
                "INSERT INTO review_versions(item_id,version,attempt_id,source_delivery,content)"
                " VALUES(%s,%s,%s,%s,%s)",
                (item_id, version, attempt_id, delivery_id, Jsonb(update.model_dump(mode="json"))),
            )
            return True

    def _reconcile_edits(self, flow_id: int, update: FeedbackUpdate) -> bool:
        """Replay a durable same-second edit chain as predecessors arrive, in the ingest transaction."""
        changed = False
        with self.store.connection() as connection:
            while True:
                row = connection.execute(
                    "SELECT i.id,i.observed_at,v.content FROM review_items i JOIN review_versions v"
                    " ON v.item_id=i.id AND v.version=i.version"
                    " WHERE i.flow_id=%s AND i.kind=%s AND i.github_id=%s",
                    (flow_id, update.kind, update.github_id),
                ).fetchone()
                assert row is not None
                current = FeedbackUpdate.model_validate(row["content"])
                connection.execute(
                    "DELETE FROM review_pending_edits WHERE item_id=%s AND (updated_at<%s OR %s)",
                    (row["id"], row["observed_at"], current.deleted),
                )
                pending = connection.execute(
                    "DELETE FROM review_pending_edits WHERE source_delivery=("
                    " SELECT source_delivery FROM review_pending_edits WHERE item_id=%s"
                    " AND updated_at=%s AND previous_body=%s ORDER BY source_delivery LIMIT 1)"
                    " RETURNING *",
                    (row["id"], row["observed_at"], current.body),
                ).fetchone()
                if pending is None:
                    return changed
                changed |= self._append_version(
                    flow_id, pending["attempt_id"], pending["source_delivery"],
                    FeedbackUpdate.model_validate(pending["content"]),
                    previous_body=pending["previous_body"],
                )

    def _has_unused_signal(self, flow_id: int) -> bool:
        with self.store.connection() as connection:
            return (
                connection.execute(
                    "SELECT 1 FROM review_items i JOIN review_versions v"
                    " ON v.item_id=i.id AND v.version=i.version WHERE i.flow_id=%s"
                    " AND v.consumed_at IS NULL AND v.relayed_at IS NULL"
                    " AND NOT (v.content->>'deleted')::boolean"
                    " AND v.content->>'signal' = 'request_changes' LIMIT 1",
                    (flow_id,),
                ).fetchone()
                is not None
            )

    def _touch(self, flow_id: int, delay: float) -> None:
        with self.store.connection() as connection:
            connection.execute(
                "INSERT INTO review_buffers(flow_id,generation,due_at) VALUES(%s,1,%s)"
                " ON CONFLICT(flow_id) DO UPDATE SET generation=review_buffers.generation+1,"
                " due_at=excluded.due_at",
                (flow_id, self.store.now() + timedelta(seconds=delay)),
            )

    def pending(self, flow_id: int) -> list[ReviewFeedback]:
        with self.store.connection() as connection:
            rows = connection.execute(
                "SELECT i.id,i.version,v.content FROM review_items i JOIN review_versions v"
                " ON v.item_id=i.id AND v.version=i.version WHERE i.flow_id=%s"
                " AND v.consumed_at IS NULL AND NOT (v.content->>'deleted')::boolean ORDER BY i.id",
                (flow_id,),
            ).fetchall()
        return [ReviewFeedback(item_id=r["id"], version=r["version"], **r["content"]) for r in rows]

    def claim_due(self) -> list[Job]:
        """Claim at most one batch per Flow, keeping the same worker→Flow→job lock order."""
        with self.store.connection() as connection:
            candidates = connection.execute(
                "SELECT flow_id FROM review_buffers WHERE due_at<=%s"
                " UNION SELECT b.flow_id FROM review_batches b JOIN flows f ON f.id=b.flow_id"
                " WHERE b.state IN ('ready','processing','waiting') AND f.state<>'active'"
                " ORDER BY flow_id",
                (self.store.now(),),
            ).fetchall()
        jobs = []
        for candidate in candidates:
            with self.store.transaction() as tx:
                flow = tx.lock_workflow(candidate["flow_id"])
                if flow is None:
                    continue
                if flow.state in TERMINAL_STATES:
                    tx.cancel_jobs(flow.id)
                    continue
                job = tx.reviews._claim(flow.id, flow.current_attempt_id)
                if job is not None:
                    jobs.append(job)
        return jobs

    def _claim(self, flow_id: int, attempt_id: int | None) -> Job | None:
        delivery = self.store.get_delivery(flow_id)
        if attempt_id is None or delivery is None or delivery.state is not DeliveryState.OPEN:
            return None
        with self.store.connection() as connection:
            buffer = connection.execute(
                "SELECT generation FROM review_buffers WHERE flow_id=%s AND due_at<=%s",
                (flow_id, self.store.now()),
            ).fetchone()
            active = connection.execute(
                "SELECT 1 FROM review_batches WHERE flow_id=%s AND state IN ('ready','processing')",
                (flow_id,),
            ).fetchone()
            if buffer is None or active is not None:
                return None
            feedback = self.pending(flow_id)
            strong = self._has_unused_signal(flow_id)
            connection.execute("UPDATE review_buffers SET due_at=NULL WHERE flow_id=%s", (flow_id,))
            if not feedback or not any(f.body.strip() for f in feedback):
                return None
            previous = connection.execute(
                "SELECT open_points FROM review_batches WHERE flow_id=%s AND state='waiting'"
                " ORDER BY id",
                (flow_id,),
            ).fetchall()
            points = list(dict.fromkeys(p for row in previous for p in row["open_points"]))
            connection.execute(
                "UPDATE review_batches SET state='completed' WHERE flow_id=%s AND state='waiting'",
                (flow_id,),
            )
            row = connection.execute(
                "INSERT INTO review_batches(flow_id,attempt_id,generation,state,trigger,feedback,"
                " open_points,created_at) VALUES(%s,%s,%s,'ready',%s,%s,%s,%s) RETURNING id",
                (
                    flow_id,
                    attempt_id,
                    buffer["generation"],
                    "strong" if strong else "discussion",
                    Jsonb([f.model_dump(mode="json") for f in feedback]),
                    Jsonb(points),
                    self.store.now(),
                ),
            ).fetchone()
            assert row is not None
            payload: dict[str, object] = {"batch_id": row["id"]}
            if strong:
                payload["instruction"] = "\n".join(
                    f"{f.author}: {f.body}" for f in feedback if f.body
                )
            job = self.store.enqueue_job(
                flow_id, JobKind.REVISION if strong else JobKind.TRIAGE, payload
            )
            connection.execute(
                "UPDATE review_batches SET job_id=%s WHERE id=%s", (job.id, row["id"])
            )
            return job

    def get_batch(self, batch_id: int) -> ReviewBatch:
        """Load persisted input content, never the live item projection."""
        with (
            self.store.connection() as connection,
            connection.cursor(row_factory=class_row(ReviewBatch)) as cursor,
        ):
            batch = cursor.execute(
                "SELECT * FROM review_batches WHERE id=%s", (batch_id,)
            ).fetchone()
        if batch is None:
            raise ValueError(f"review batch {batch_id} does not exist")
        return batch

    def for_job(self, job: Job) -> ReviewBatch:
        """Verify that this job, rather than an earlier stage or retry, owns the batch."""
        batch_id = (job.payload or {}).get("batch_id")
        if type(batch_id) is not int:
            raise ValueError(
                f"review job {job.id} has no frozen batch; drain legacy work before upgrade"
            )
        batch = self.get_batch(batch_id)
        if batch.flow_id != job.flow_id or batch.job_id != job.id:
            raise ValueError("review job does not own its batch")
        return batch

    def freeze_threads(self, job: Job, snapshot: ReviewThreads) -> ReviewThreads:
        """Bind remote thread/comment identities to this batch before worker execution."""
        batch = self.for_job(job)
        with self.store.connection() as connection:
            connection.execute(
                "UPDATE review_batches SET threads=COALESCE(threads,%s) WHERE id=%s",
                (Jsonb(snapshot.model_dump(mode="json")), batch.id),
            )
        return batch.threads or snapshot

    def addressed(self, flow_id: int, attempt_id: int) -> list[ReviewFeedback]:
        """Only current versions addressed by verified deliveries may cover later thread checks."""
        with self.store.connection() as connection:
            rows = connection.execute(
                "SELECT i.id,i.version,v.content FROM review_items i JOIN review_versions v"
                " ON v.item_id=i.id AND v.version=i.version WHERE i.flow_id=%s"
                " AND v.attempt_id=%s AND v.addressed_sha IS NOT NULL",
                (flow_id, attempt_id),
            ).fetchall()
        return [ReviewFeedback(item_id=r["id"], version=r["version"], **r["content"]) for r in rows]

    def record_addressed(
        self, batch_id: int, refs: list[FeedbackRef], sha: str, job_id: int,
    ) -> None:
        batch = self.get_batch(batch_id)
        members = {(f.item_id, f.version) for f in batch.feedback}
        with self.store.connection() as connection:
            for ref in refs:
                if (ref.item_id, ref.version) not in members:
                    raise ValueError("addressed feedback is outside batch")
                connection.execute(
                    "UPDATE review_versions SET addressed_sha=%s,addressed_job_id=%s"
                    " WHERE item_id=%s AND version=%s", (sha, job_id, ref.item_id, ref.version),
                )

    def observe_threads(
        self, flow_id: int, snapshot: ReviewThreads, baseline: list[ReviewFeedback],
    ) -> None:
        """Persist remote facts and missing human input without consuming or reviving old versions.

        Runs under the caller's workflow lock. Even manually resolved threads can contain new input.
        Observations never manufacture an addressed or remote-resolution receipt from legacy flags.
        """
        flow = self.store.get_flow(flow_id)
        delivery = self.store.get_delivery(flow_id)
        if (flow is None or flow.current_attempt_id is None or delivery is None
                or snapshot.repo != flow.repo or snapshot.pr_number != delivery.pr_number):
            raise ValueError("thread observation does not belong to active PR")
        if delivery.state is DeliveryState.MERGED:
            return
        changed = False
        frozen = {(f.item_id, f.version) for f in baseline if f.kind is ReviewItemKind.INLINE}
        with self.store.connection() as connection:
            for thread in snapshot.threads:
                connection.execute(
                    "INSERT INTO review_thread_observations VALUES(%s,%s,%s,%s)"
                    " ON CONFLICT(flow_id,thread_id) DO UPDATE SET fetched_at=EXCLUDED.fetched_at,"
                    " snapshot=EXCLUDED.snapshot WHERE review_thread_observations.fetched_at"
                    " <= EXCLUDED.fetched_at",
                    (flow_id, thread.thread_id, snapshot.fetched_at,
                     Jsonb(thread.model_dump(mode="json"))),
                )
                for comment in thread.comments:
                    if comment.is_bot:
                        continue
                    row = connection.execute(
                        "SELECT i.id,i.version,i.observed_at,v.content FROM review_items i JOIN review_versions v"
                        " ON i.id=v.item_id AND i.version=v.version WHERE i.flow_id=%s"
                        " AND i.kind='inline' AND i.github_id=%s", (flow_id, comment.github_id),
                    ).fetchone()
                    old = FeedbackUpdate.model_validate(row["content"]) if row else None
                    if old and (old.body, old.author, old.updated_at) == (
                        comment.body, comment.author, comment.updated_at,
                    ):
                        # Thread metadata is stored above; enriching it is not new reviewer input.
                        changed |= self._reconcile_edits(flow_id, old)
                        continue
                    if (row and row["observed_at"] == comment.updated_at
                            and (row["id"], row["version"]) not in frozen):
                        # A webhook may be ahead of an eventually consistent GraphQL read in the
                        # same timestamp tick. Only advance the frozen version, never undo a newer one.
                        continue
                    update = FeedbackUpdate(
                        kind=ReviewItemKind.INLINE, github_id=comment.github_id,
                        author=comment.author, body=comment.body, updated_at=comment.updated_at,
                        path=thread.path, original_commit_id=comment.original_commit_id,
                        diff_hunk=old.diff_hunk if old else None,
                        signal=old.signal if old else "discussion",
                    )
                    changed |= self._append_version(
                        flow_id, flow.current_attempt_id, None, update,
                        previous_body=old.body if old else None,
                    )
                    changed |= self._reconcile_edits(flow_id, update)
            if changed:
                self._touch(flow_id, 0)

    def started(self, job: Job) -> bool:
        """Record model relay once per job stage; return whether this is its first Started."""
        batch = self.for_job(job)
        if batch.state is BatchState.PROCESSING:
            return False
        if batch.state is not BatchState.READY:
            raise ValueError("cannot start an inactive review batch")
        with self.store.connection() as connection:
            connection.execute(
                "UPDATE review_batches SET state='processing' WHERE id=%s", (batch.id,)
            )
            for item in batch.feedback:
                connection.execute(
                    "UPDATE review_versions SET relayed_at=COALESCE(relayed_at,%s)"
                    " WHERE item_id=%s AND version=%s",
                    (self.store.now(), item.item_id, item.version),
                )
        return True

    def freeze_context(self, job: Job, context: ReviewContext) -> ReviewContext:
        """Called with the workflow lock after network reads; first prepared snapshot wins."""
        batch = self.for_job(job)
        if context.batch_id != batch.id or batch.state not in {
            BatchState.READY, BatchState.PROCESSING,
        }:
            raise ValueError("cannot freeze context for an inactive/different batch")
        if batch.context is not None:
            return batch.context
        with self.store.connection() as connection:
            connection.execute("UPDATE review_batches SET context=%s WHERE id=%s",
                               (Jsonb(context.model_dump(mode="json")), batch.id))
        return context

    def record_decision(self, job: Job, decision: JudgeDecision) -> None:
        """Persist the accepted interpretation alongside its immutable input in the result transaction."""
        batch = self.for_job(job)
        if batch.context is None or batch.context.digest != decision.context_digest:
            raise ValueError("decision does not match its frozen context")
        with self.store.connection() as connection:
            connection.execute("UPDATE review_batches SET decision=%s,open_points=%s WHERE id=%s",
                (Jsonb(decision.model_dump(mode="json")), Jsonb(decision.verdict.open_points), batch.id))

    def advance(self, batch_id: int, job: Job) -> None:
        """Transfer a batch to its one derived job without releasing the active-batch constraint."""
        with self.store.connection() as connection:
            connection.execute(
                "UPDATE review_batches SET job_id=%s,state='ready' WHERE id=%s", (job.id, batch_id)
            )

    def retry(self, previous: Job, replacement: Job) -> None:
        """An explicit retry reuses its frozen inputs and preserves later buffered versions."""
        batch = self.for_job(previous)
        self.advance(batch.id, replacement)
        frozen = {(f.item_id, f.version) for f in batch.feedback}
        if any((f.item_id, f.version) not in frozen for f in self.pending(batch.flow_id)):
            self._touch(batch.flow_id, 0)

    def freeze_revision(self, job: Job, task: RevisionTask) -> RevisionTask:
        """Persist the non-secret assignment before dispatch under the workflow lock."""
        self.for_job(job)
        if job.payload is not None and job.payload.get("revision") is not None:
            return RevisionTask.model_validate(job.payload["revision"])
        payload = {**(job.payload or {}), "revision": task.model_dump(mode="json")}
        with self.store.connection() as connection:
            connection.execute("UPDATE jobs SET payload=%s WHERE id=%s", (Jsonb(payload), job.id))
        job.payload = payload
        return task

    def mark_context_stale(self, job: Job) -> None:
        """Retain the old evidence while recording that explicit retry needs a new batch."""
        batch = self.for_job(job)
        with self.store.connection() as connection:
            connection.execute("UPDATE review_batches SET context_stale=TRUE WHERE id=%s", (batch.id,))

    def retriage(self, previous: Job) -> None:
        """Under the workflow lock, feed stale unconsumed input into normal batch creation."""
        batch = self.for_job(previous)
        with self.store.connection() as connection:
            connection.execute("UPDATE review_batches SET state='waiting' WHERE id=%s", (batch.id,))
        self._touch(batch.flow_id, 0)
        self._claim(batch.flow_id, batch.attempt_id)

    def complete(
        self,
        batch_id: int,
        state: BatchState,
        consumed: list[FeedbackRef],
        open_points: list[str],
    ) -> None:
        """Apply exact version acknowledgements within the caller's workflow transaction."""
        batch = self.get_batch(batch_id)
        members = {(f.item_id, f.version) for f in batch.feedback}
        if any((f.item_id, f.version) not in members for f in consumed):
            raise ValueError("result tried to consume feedback outside its frozen batch")
        with self.store.connection() as connection:
            for item in consumed:
                connection.execute(
                    "UPDATE review_versions SET consumed_at=COALESCE(consumed_at,%s)"
                    " WHERE item_id=%s AND version=%s",
                    (self.store.now(), item.item_id, item.version),
                )
            connection.execute(
                "UPDATE review_batches SET state=%s,open_points=%s WHERE id=%s",
                (state, Jsonb(open_points), batch_id),
            )

    def cancel(self, flow_id: int) -> None:
        """Retire pending discussion atomically with the Flow's terminal transition."""
        with self.store.connection() as connection:
            connection.execute("UPDATE review_buffers SET due_at=NULL WHERE flow_id=%s", (flow_id,))
            connection.execute(
                "UPDATE review_batches SET state='cancelled' WHERE flow_id=%s"
                " AND state IN ('ready','processing','waiting')",
                (flow_id,),
            )

    def check_upgrade(self) -> None:
        """Fail with actionable job IDs instead of inventing missing legacy batch identities."""
        with self.store.connection() as connection:
            rows = connection.execute(
                "SELECT id FROM jobs j WHERE (kind IN ('triage','revision','answer')"
                " AND (state IN ('queued','running') OR (state='failed'"
                " AND id=(SELECT MAX(newer.id) FROM jobs newer WHERE newer.flow_id=j.flow_id)"
                " AND EXISTS (SELECT 1 FROM flows f WHERE f.id=j.flow_id"
                " AND f.state IN ('failed','cancelled')))) AND (payload->>'batch_id') IS NULL)"
                " OR (result_received_at IS NOT NULL AND result_applied_at IS NULL"
                " AND result_payload->>'protocol_version' IS DISTINCT FROM '8')"
                " OR (kind='revision' AND state='running' AND started_at IS NOT NULL"
                " AND (payload->>'revision') IS NULL)"
                " OR (kind='archive' AND state='running' AND (payload->>'archive') IS NULL)"
                " OR (kind='answer' AND state IN ('queued','running','failed'))"
                " OR (j.result_received_at IS NOT NULL AND j.result_applied_at IS NULL"
                " AND EXISTS (SELECT 1 FROM result_applications a WHERE a.job_id=j.id"
                " AND a.plan->'revision' != 'null'::jsonb"
                " AND a.plan->>'resolution_version' IS DISTINCT FROM '1'))"
                " OR (kind='triage' AND state='running' AND started_at IS NOT NULL AND NOT EXISTS"
                " (SELECT 1 FROM review_batches b WHERE b.job_id=j.id AND b.context IS NOT NULL))"
                " ORDER BY id",
            ).fetchall()
        if rows:
            raise RuntimeError(
                "Drain or reconcile pre-upgrade jobs before starting: "
                + ", ".join(str(row["id"]) for row in rows)
            )

    def migrate_legacy(self) -> None:
        """Import latest legacy objects once, retaining historical rows and unverified resolution."""
        with self.store.transaction() as tx, tx.connection() as connection:
            if (
                connection.execute(
                    "INSERT INTO review_migrations(version) VALUES(1) ON CONFLICT DO NOTHING RETURNING version"
                ).fetchone()
                is None
            ):
                return
            rows = connection.execute(
                "SELECT DISTINCT ON (a.flow_id,r.kind,r.github_id) r.*,a.flow_id"
                " FROM review_threads r JOIN attempts a ON a.id=r.attempt_id"
                " ORDER BY a.flow_id,r.kind,r.github_id,r.attempt_id DESC,r.id DESC"
            ).fetchall()
            for row in rows:
                update = FeedbackUpdate(
                    kind=row["kind"],
                    github_id=row["github_id"],
                    author=row["author"],
                    body=row["body"],
                    updated_at=row["created_at"],
                    path=row["path"],
                    original_commit_id=row["original_commit_id"],
                    diff_hunk=row["diff_hunk"],
                )
                tx.reviews._append_version(row["flow_id"], row["attempt_id"], None, update)
                if row["relayed"]:
                    connection.execute(
                        "UPDATE review_versions SET consumed_at=%s,relayed_at=%s WHERE item_id IN"
                        " (SELECT id FROM review_items WHERE flow_id=%s AND kind=%s AND github_id=%s)",
                        (tx.now(), tx.now(), row["flow_id"], row["kind"], row["github_id"]),
                    )
                else:
                    tx.reviews._touch(row["flow_id"], 0)
