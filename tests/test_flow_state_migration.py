@pytest.mark.parametrize("old_state", ["cancelled", "succeeded"])
@pytest.mark.parametrize(
    "hazard",
    [
        "pending-result",
        "pending-stop",
        "missing-stop-receipt",
        "effect-uncertain",
        "effect-skipped-without-receipt",
        "retained-workspace",
        "missing-cleanup",
        "worker-slot",
        "digest",
        "frozen-identity",
    ],
)
def test_terminal_label_never_substitutes_for_disposition(
    legacy, postgresql_url, old_state, hazard
):
    identity, job_id = succeeded(legacy)
    if old_state == "cancelled":
        legacy.execute("UPDATE flows SET state='cancelled' WHERE id=%s", (identity,))
        legacy.execute("UPDATE flow_deliveries SET state='closed' WHERE flow_id=%s", (identity,))
        legacy.execute(
            "UPDATE result_applications SET plan=jsonb_set(plan,'{flow_state}','null') WHERE job_id=%s",
            (job_id,),
        )
    if hazard == "pending-result":
        legacy.execute("UPDATE jobs SET result_applied_at=NULL WHERE id=%s", (job_id,))
    elif hazard in {"pending-stop", "missing-stop-receipt"}:
        legacy.execute(
            "INSERT INTO execution_stops(request_id,flow_id,job_id,worker_id,assignment_token,binding_at,"
            "requested_at,state,confirmed_at) VALUES ('stop',%s,%s,%s,'token',%s,%s,%s,%s)",
            (
                identity,
                job_id,
                f"worker-{identity}",
                NOW,
                NOW,
                "pending" if hazard == "pending-stop" else "confirmed",
                NOW,
            ),
        )
    elif hazard.startswith("effect-"):
        legacy.execute(
            "INSERT INTO result_effects(job_id,effect_key,position,payload,state,dispatched_at,next_attempt_at) "
            "VALUES (%s,'notification',0,'{}',%s,%s,%s)",
            (job_id, "uncertain" if hazard == "effect-uncertain" else "skipped", NOW, NOW),
        )
    elif hazard == "retained-workspace":
        legacy.execute("UPDATE flow_executions SET released_at=NULL WHERE flow_id=%s", (identity,))
    elif hazard == "missing-cleanup":
        if old_state == "cancelled":
            legacy.execute(
                "UPDATE jobs SET result_applied_at=NULL,result_received_at=NULL,result_payload=NULL WHERE id=%s",
                (job_id,),
            )
        else:
            legacy.execute(
                "UPDATE result_applications SET plan=plan-'archive' WHERE job_id=%s", (job_id,)
            )
    elif hazard == "worker-slot":
        legacy.execute(
            "UPDATE workers SET current_job_id=%s WHERE worker_id=%s",
            (job_id, f"worker-{identity}"),
        )
    elif hazard == "digest":
        legacy.execute("UPDATE jobs SET result_digest='invalid' WHERE id=%s", (job_id,))
    elif hazard == "frozen-identity":
        # A released row cannot prove disposition of an assignment to another worker.
        legacy.execute("UPDATE jobs SET assigned_worker_id='other' WHERE id=%s", (job_id,))
    before = snapshot(legacy)
    report = migrate(postgresql_url)
    assert report.status == "refused", report.as_dict()
    assert any(identity in p["flow_ids"] for p in report.problems)
    assert (
        migrate(postgresql_url, apply=True, expected_fingerprint=report.fingerprint).status
        == "refused"
    )
    assert snapshot(legacy) == before


