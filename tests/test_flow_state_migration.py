def applied_plan(connection, identity, attempt, job_id, *, old_state=None, archive=None):
    """Real inbox digests and serialized plans, including fields untouched by conversion."""
    terminal = (
        Failed(job_id=job_id, assignment_token="token", error="failed")
        if old_state == "failed"
        else Succeeded(
            job_id=job_id,
            assignment_token="token",
            result=archive
            or InitialTaskResult(
                session_id="session",
                exit_code=0,
                last_message="done",
            ),
        )
    )
    digest = terminal_digest(terminal)
    connection.execute(
        "UPDATE jobs SET state=%s,assignment_token='token',result_payload=%s,result_digest=%s,"
        " result_received_at=%s,result_applied_at=%s WHERE id=%s",
        (
            "failed" if old_state == "failed" else "done",
            Jsonb(ResultInbox(source="worker", terminal=terminal).model_dump(mode="json")),
            digest,
            NOW + timedelta(seconds=10),
            NOW + timedelta(seconds=20),
            job_id,
        ),
    )
    plan = {
        "job_id": job_id,
        "flow_id": identity,
        "attempt_id": attempt,
        "digest": digest,
        "state": "failed" if old_state == "failed" else "done",
        "flow_state": old_state,
        "error": "historical intent",
        "effects": [],
        "archive": archive.model_dump(mode="json") if archive else None,
    }
    connection.execute(
        "INSERT INTO result_applications(job_id,digest,plan,created_at) VALUES (%s,%s,%s,%s)",
        (job_id, digest, Jsonb(plan), NOW),
    )
    return plan


def succeeded(connection, issue=1, *, cleanup="released"):
    identity, attempt = flow(connection, "succeeded", issue)
    worker = binding(connection, identity, released=True)
    delivery(connection, identity, state="merged")
    job_id = job(connection, identity, kind="archive", state="done")
    receipt = ArchiveResult(
        flow_id=identity,
        attempt_id=attempt,
        repo="owner/repo",
        worker_id=worker,
        repo_identity=f"{worker}:owner/repo",
        delivery_version=0,
        cleanup=cleanup,
    )
    connection.execute(
        "UPDATE jobs SET assigned_worker_id=%s,started_at=%s,payload=%s WHERE id=%s",
        (worker, NOW, Jsonb({"archive": receipt.model_dump(exclude={"cleanup"})}), job_id),
    )
    applied_plan(connection, identity, attempt, job_id, old_state="succeeded", archive=receipt)
    return identity, job_id


def snapshot(connection):
    """Include DDL and all business/publication rows to prove refusal/rollback is nonmutating."""
    tables = [
        r["tablename"]
        for r in connection.execute(
            "SELECT tablename FROM pg_tables WHERE schemaname=current_schema() ORDER BY tablename"
        )
    ]
    return {
        "rows": {
            t: connection.execute(
                sql.SQL("SELECT to_jsonb(t) AS data FROM {} t ORDER BY to_jsonb(t)::text").format(
                    sql.Identifier(t)
                )
            ).fetchall()
            for t in tables
        },
        "columns": connection.execute(
            "SELECT table_name,column_name,column_default FROM information_schema.columns "
            "WHERE table_schema=current_schema() ORDER BY table_name,ordinal_position"
        ).fetchall(),
        "indexes": connection.execute(
            "SELECT indexname,indexdef FROM pg_indexes WHERE schemaname=current_schema() "
            "ORDER BY indexname"
        ).fetchall(),
        "views": connection.execute(
            "SELECT viewname,definition FROM pg_views WHERE schemaname=current_schema() "
            "ORDER BY viewname"
        ).fetchall(),
        "constraints": connection.execute(
            "SELECT conname,pg_get_constraintdef(c.oid) AS definition FROM pg_constraint c "
            "JOIN pg_namespace n ON n.oid=c.connamespace WHERE n.nspname=current_schema() "
            "ORDER BY conname,definition"
        ).fetchall(),
        "functions": connection.execute(
            "SELECT p.proname,pg_get_functiondef(p.oid) AS definition FROM pg_proc p "
            "JOIN pg_namespace n ON n.oid=p.pronamespace "
            "WHERE n.nspname=current_schema() AND p.prokind='f' ORDER BY p.proname,definition"
        ).fetchall(),
        "triggers": connection.execute(
            "SELECT c.relname,t.tgname,pg_get_triggerdef(t.oid) AS definition FROM pg_trigger t "
            "JOIN pg_class c ON c.oid=t.tgrelid JOIN pg_namespace n ON n.oid=c.relnamespace "
            "WHERE n.nspname=current_schema() AND NOT t.tgisinternal ORDER BY c.relname,t.tgname"
        ).fetchall(),
    }


