def flow(connection, state="active", issue=1, created=NOW, *, with_attempt=True):
    row = connection.execute(
        "INSERT INTO flows(repo,issue_number,installation_id,state,created_at,updated_at) "
        "VALUES ('owner/repo',%s,42,%s,%s,%s) RETURNING id",
        (issue, state, created, created),
    ).fetchone()
    identity = row["id"]
    if not with_attempt:
        return identity, None
    attempt = connection.execute(
        "INSERT INTO attempts(flow_id,created_at,updated_at) VALUES (%s,%s,%s) RETURNING id",
        (identity, created, created),
    ).fetchone()["id"]
    connection.execute("UPDATE flows SET current_attempt_id=%s WHERE id=%s", (attempt, identity))
    return identity, attempt


def job(connection, identity, *, kind="initial", state="queued"):
    return connection.execute(
        "INSERT INTO jobs(flow_id,kind,state,created_at,updated_at) VALUES (%s,%s,%s,%s,%s) RETURNING id",
        (identity, kind, state, NOW, NOW),
    ).fetchone()["id"]


def binding(connection, identity, *, released=False):
    worker = f"worker-{identity}"
    connection.execute(
        "INSERT INTO workers(worker_id,protocol_version,status,first_connected_at,last_connected_at,last_seen_at) "
        "VALUES (%s,16,'online',%s,%s,%s)",
        (worker, NOW, NOW, NOW),
    )
    connection.execute(
        "INSERT INTO flow_executions(flow_id,worker_id,repo_identity,bound_at,released_at) VALUES (%s,%s,%s,%s,%s)",
        (
            identity,
            worker,
            f"{worker}:owner/repo",
            NOW,
            NOW + timedelta(minutes=1) if released else None,
        ),
    )
    return worker


